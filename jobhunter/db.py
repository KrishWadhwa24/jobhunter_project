"""Storage: PostgreSQL when DATABASE_URL is set, otherwise a local SQLite file.

Queries are written once with `?` placeholders; the wrapper below translates them for Postgres.
"""
from __future__ import annotations

import json
import sqlite3
import threading
from contextlib import contextmanager
from typing import Any, Dict, Iterable, Iterator, List, Optional

from . import config
from .util import utcnow

_SCHEMA = """
CREATE TABLE IF NOT EXISTS companies (
  id {PK},
  name TEXT NOT NULL UNIQUE,
  category TEXT DEFAULT '',
  pay_tier TEXT DEFAULT '',
  source_type TEXT NOT NULL DEFAULT 'browser',
  slug_or_endpoint TEXT DEFAULT '',
  careers_url TEXT DEFAULT '',
  verified TEXT DEFAULT 'no',
  active INTEGER NOT NULL DEFAULT 1,
  notes TEXT DEFAULT '',
  last_fetch_at TEXT,
  last_status TEXT DEFAULT 'never',      -- never | ok | error | skipped
  last_error TEXT DEFAULT '',
  last_job_count INTEGER DEFAULT 0,
  last_relevant_count INTEGER DEFAULT 0,
  consecutive_failures INTEGER DEFAULT 0,
  health_alerted INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS jobs (
  id {PK},
  company_id {FK} NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  external_id TEXT NOT NULL,
  title TEXT NOT NULL,
  url TEXT NOT NULL,
  location TEXT DEFAULT '',
  description TEXT DEFAULT '',
  posted_at TEXT,
  first_seen_at TEXT NOT NULL,
  last_seen_at TEXT NOT NULL,
  is_open INTEGER NOT NULL DEFAULT 1,
  in_scope INTEGER NOT NULL DEFAULT 0,    -- passed role + India checks (stored with a level)
  level TEXT DEFAULT '',                  -- intern | sde1 | sde2 | sde3 | staff | unknown
  verdict TEXT DEFAULT '',                -- match | maybe | reject
  score INTEGER DEFAULT 0,
  reasons TEXT DEFAULT '[]',
  flags TEXT DEFAULT '{}',
  state TEXT NOT NULL DEFAULT 'new',      -- new | referral | apply_queued | applied | hidden
  alerted_at TEXT,
  detail_fetched INTEGER NOT NULL DEFAULT 0,
  UNIQUE(company_id, external_id)
);

CREATE INDEX IF NOT EXISTS idx_jobs_state ON jobs(state, in_scope, is_open);
CREATE INDEX IF NOT EXISTS idx_jobs_level ON jobs(level);

CREATE TABLE IF NOT EXISTS job_events (
  id {PK},
  job_id {FK} NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  ts TEXT NOT NULL,
  event TEXT NOT NULL,
  note TEXT DEFAULT ''
);

CREATE TABLE IF NOT EXISTS kv (key TEXT PRIMARY KEY, value TEXT);

CREATE TABLE IF NOT EXISTS resumes (
  id {PK},
  job_id {FK} NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'working',      -- working | ready | failed
  score REAL DEFAULT 0,
  target_reached INTEGER DEFAULT 0,
  details TEXT DEFAULT '{}',
  pdf_path TEXT DEFAULT '',
  docx_path TEXT DEFAULT '',
  error TEXT DEFAULT ''
);

CREATE TABLE IF NOT EXISTS applications (
  id {PK},
  job_id {FK} NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'queued',     -- queued | tailoring | filling | ready | needs_you | failed
  report TEXT DEFAULT '{}',
  error TEXT DEFAULT ''
)
"""


def backend() -> str:
    u = config.database_url().lower()
    return "pg" if u.startswith(("postgres://", "postgresql://")) else "sqlite"


def schema_statements() -> List[str]:
    if backend() == "pg":
        sql = _SCHEMA.replace("{PK}", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY").replace("{FK}", "BIGINT")
    else:
        sql = _SCHEMA.replace("{PK}", "INTEGER PRIMARY KEY AUTOINCREMENT").replace("{FK}", "INTEGER")
    return [x.strip() for x in sql.split(";") if x.strip()]


class Conn:
    """Thin wrapper so the rest of the code is backend-agnostic."""

    def __init__(self, raw: Any, kind: str) -> None:
        self.raw, self.kind = raw, kind

    def execute(self, sql: str, params: Iterable[Any] = ()) -> Any:
        if self.kind == "pg":
            sql = sql.replace("?", "%s")
        return self.raw.execute(sql, tuple(params))

    def insert(self, sql: str, params: Iterable[Any] = ()) -> int:
        """INSERT and return the new row id."""
        if self.kind == "pg":
            cur = self.execute(sql + " RETURNING id", params)
            return int(cur.fetchone()["id"])
        return int(self.execute(sql, params).lastrowid)


_pools: Dict[str, Any] = {}
_pool_lock = threading.Lock()


def _pool() -> Any:
    url = config.database_url()
    with _pool_lock:
        if url not in _pools:
            from psycopg.rows import dict_row
            from psycopg_pool import ConnectionPool
            pool = ConnectionPool(url, min_size=1, max_size=12, kwargs={"row_factory": dict_row, "client_encoding": "UTF8"}, open=False)
            pool.open(wait=True, timeout=15)
            _pools[url] = pool
        return _pools[url]


def close_pools() -> None:
    with _pool_lock:
        for p in _pools.values():
            p.close()
        _pools.clear()


@contextmanager
def connect() -> Iterator[Conn]:
    if backend() == "pg":
        with _pool().connection() as raw:      # commits on success, rolls back on error
            yield Conn(raw, "pg")
        return
    config.ensure_dirs()
    raw = sqlite3.connect(str(config.DB_PATH), timeout=30)
    raw.row_factory = sqlite3.Row
    raw.execute("PRAGMA journal_mode=WAL")
    raw.execute("PRAGMA foreign_keys=ON")
    try:
        yield Conn(raw, "sqlite")
        raw.commit()
    except Exception:
        raw.rollback()
        raise
    finally:
        raw.close()


def init_db() -> None:
    with connect() as c:
        if c.kind == "pg":
            c.execute("SET LOCAL lock_timeout = '10s'")     # never hang forever behind another process
        try:
            for stmt in schema_statements():
                c.execute(stmt)
        except Exception as e:
            if "lock timeout" in str(e).lower():
                raise RuntimeError("The database is busy: another Jobhunter process (probably an older service that "
                                   "did not stop) is holding it. Run `make service-stop` and try again.") from e
            raise


def describe() -> str:
    """Human-readable description of where data lives (password hidden)."""
    return config.redact(config.database_url()) if backend() == "pg" else f"SQLite file {config.DB_PATH}"


# ---------- key/value ----------
def kv_get(key: str, default: Optional[str] = None) -> Optional[str]:
    with connect() as c:
        r = c.execute("SELECT value FROM kv WHERE key=?", (key,)).fetchone()
    return r["value"] if r else default


def kv_set(key: str, value: str) -> None:
    with connect() as c:
        c.execute("INSERT INTO kv(key,value) VALUES(?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value",
                  (key, value))


# ---------- companies ----------
COMPANY_FIELDS = ["name", "category", "pay_tier", "source_type", "slug_or_endpoint", "careers_url",
                  "verified", "active", "notes"]


def upsert_company(row: Dict[str, Any]) -> int:
    """Insert or update by (case-insensitive) name. Keeps health fields on update."""
    name = (row.get("name") or "").strip()
    if not name:
        raise ValueError("company name required")
    vals = {k: row.get(k, "") for k in COMPANY_FIELDS}
    vals["name"] = name
    vals["active"] = 1 if str(row.get("active", "yes")).strip().lower() in ("1", "yes", "true", "y") else 0
    vals["source_type"] = (vals["source_type"] or "browser").strip().lower()
    with connect() as c:
        ex = c.execute("SELECT id FROM companies WHERE lower(name)=lower(?)", (name,)).fetchone()
        if ex:
            fields = [k for k in COMPANY_FIELDS if k != "name"]      # keep the original spelling of the name
            sets = ", ".join(f"{k}=?" for k in fields)
            c.execute(f"UPDATE companies SET {sets} WHERE id=?", [vals[k] for k in fields] + [ex["id"]])
            return int(ex["id"])
        cols = ", ".join(COMPANY_FIELDS)
        qs = ", ".join("?" for _ in COMPANY_FIELDS)
        return c.insert(f"INSERT INTO companies({cols}) VALUES({qs})", [vals[k] for k in COMPANY_FIELDS])


def get_company(company_id: int) -> Optional[Dict[str, Any]]:
    with connect() as c:
        return c.execute("SELECT * FROM companies WHERE id=?", (company_id,)).fetchone()


def list_companies(active_only: bool = False) -> List[Dict[str, Any]]:
    q = "SELECT * FROM companies"
    if active_only:
        q += " WHERE active=1"
    q += " ORDER BY lower(name)"
    with connect() as c:
        return c.execute(q).fetchall()


def set_company_active(company_id: int, active: bool) -> None:
    with connect() as c:
        c.execute("UPDATE companies SET active=? WHERE id=?", (1 if active else 0, company_id))


def update_company_health(company_id: int, status: str, error: str = "", job_count: int = 0,
                          relevant: int = 0) -> Dict[str, Any]:
    with connect() as c:
        row = c.execute("SELECT consecutive_failures FROM companies WHERE id=?", (company_id,)).fetchone()
        fails = (row["consecutive_failures"] if row else 0)
        fails = fails + 1 if status == "error" else (0 if status == "ok" else fails)   # "network" and "skipped" leave it alone
        c.execute(
            """UPDATE companies SET last_fetch_at=?, last_status=?, last_error=?, last_job_count=?,
               last_relevant_count=?, consecutive_failures=?, health_alerted=CASE WHEN ?='ok' THEN 0 ELSE health_alerted END
               WHERE id=?""",
            (utcnow(), status, error[:500], job_count, relevant, fails, status, company_id))
        return c.execute("SELECT * FROM companies WHERE id=?", (company_id,)).fetchone()


def mark_health_alerted(company_id: int) -> None:
    with connect() as c:
        c.execute("UPDATE companies SET health_alerted=1 WHERE id=?", (company_id,))


# ---------- jobs ----------
def get_job(job_id: int) -> Optional[Dict[str, Any]]:
    with connect() as c:
        return c.execute(
            "SELECT j.*, c.name AS company, c.pay_tier AS tier, c.careers_url AS careers_url "
            "FROM jobs j JOIN companies c ON c.id=j.company_id WHERE j.id=?", (job_id,)).fetchone()


def add_event(job_id: int, event: str, note: str = "") -> None:
    with connect() as c:
        c.execute("INSERT INTO job_events(job_id, ts, event, note) VALUES(?,?,?,?)", (job_id, utcnow(), event, note))


def job_events(job_id: int) -> List[Dict[str, Any]]:
    with connect() as c:
        return c.execute("SELECT * FROM job_events WHERE job_id=? ORDER BY id DESC", (job_id,)).fetchall()


def set_job_state(job_id: int, state: str, note: str = "") -> None:
    with connect() as c:
        c.execute("UPDATE jobs SET state=? WHERE id=?", (state, job_id))
    add_event(job_id, f"state:{state}", note)


def query_jobs(states: Iterable[str], levels: Iterable[str], verdicts: Iterable[str],
               company_id: Optional[int] = None, only_open: bool = True, limit: int = 200,
               search: str = "") -> List[Dict[str, Any]]:
    states, levels, verdicts = list(states), list(levels), list(verdicts)
    where = ["j.in_scope=1"]
    args: List[Any] = []
    if only_open:
        where.append("j.is_open=1")
    if states:
        where.append("j.state IN (%s)" % ",".join("?" * len(states)))
        args += states
    if levels:
        where.append("j.level IN (%s)" % ",".join("?" * len(levels)))
        args += levels
    if verdicts:
        where.append("j.verdict IN (%s)" % ",".join("?" * len(verdicts)))
        args += verdicts
    if company_id:
        where.append("j.company_id=?")
        args.append(company_id)
    if search:
        where.append("(lower(j.title) LIKE ? OR lower(c.name) LIKE ?)")
        args += [f"%{search.lower()}%"] * 2
    sql = ("SELECT j.*, c.name AS company, c.pay_tier AS tier FROM jobs j JOIN companies c ON c.id=j.company_id "
           "WHERE " + " AND ".join(where) + " ORDER BY j.score DESC, j.first_seen_at DESC LIMIT ?")
    args.append(limit)
    with connect() as c:
        return c.execute(sql, args).fetchall()


def job_counts() -> Dict[str, int]:
    with connect() as c:
        r = c.execute(
            """SELECT
               SUM(CASE WHEN in_scope=1 AND is_open=1 THEN 1 ELSE 0 END) AS in_scope,
               SUM(CASE WHEN in_scope=1 AND is_open=1 AND verdict='match' AND state='new' THEN 1 ELSE 0 END) AS new_matches,
               SUM(CASE WHEN state='referral' THEN 1 ELSE 0 END) AS referral,
               SUM(CASE WHEN state='applied' THEN 1 ELSE 0 END) AS applied,
               COUNT(*) AS total FROM jobs""").fetchone()
    return {k: (r[k] or 0) for k in r.keys()}


def loads(s: Optional[str], default: Any) -> Any:
    try:
        return json.loads(s) if s else default
    except (TypeError, ValueError):
        return default


# ---- tailored resumes ----
def resume_start(job_id: int) -> int:
    with connect() as c:
        return c.insert("INSERT INTO resumes(job_id, created_at, status) VALUES(?,?, 'working')", (job_id, utcnow()))


def resume_finish(resume_id: int, status: str, score: float = 0.0, target_reached: bool = False,
                  details: Optional[Dict[str, Any]] = None, pdf_path: str = "", docx_path: str = "",
                  error: str = "") -> None:
    with connect() as c:
        c.execute("UPDATE resumes SET status=?, score=?, target_reached=?, details=?, pdf_path=?, docx_path=?, error=? "
                  "WHERE id=?", (status, float(score), 1 if target_reached else 0, json.dumps(details or {}, default=str),
                                 pdf_path, docx_path, error[:500], resume_id))


def get_resume(job_id: int) -> Optional[Dict[str, Any]]:
    with connect() as c:
        row = c.execute("SELECT * FROM resumes WHERE job_id=? ORDER BY id DESC LIMIT 1", (job_id,)).fetchone()
    if not row:
        return None
    out = dict(row)
    out["details"] = loads(out.get("details"), {})
    return out


# ---- application auto-fill runs ----
def application_start(job_id: int) -> int:
    now = utcnow()
    with connect() as c:
        return c.insert("INSERT INTO applications(job_id, created_at, updated_at, status) VALUES(?,?,?, 'queued')",
                        (job_id, now, now))


def application_update(app_id: int, status: str, report: Optional[Dict[str, Any]] = None, error: str = "") -> None:
    with connect() as c:
        if report is None:
            c.execute("UPDATE applications SET status=?, updated_at=?, error=? WHERE id=?",
                      (status, utcnow(), error[:500], app_id))
        else:
            c.execute("UPDATE applications SET status=?, updated_at=?, report=?, error=? WHERE id=?",
                      (status, utcnow(), json.dumps(report, default=str), error[:500], app_id))


def get_application(job_id: int) -> Optional[Dict[str, Any]]:
    with connect() as c:
        row = c.execute("SELECT * FROM applications WHERE job_id=? ORDER BY id DESC LIMIT 1", (job_id,)).fetchone()
    if not row:
        return None
    out = dict(row)
    out["report"] = loads(out.get("report"), {})
    return out
